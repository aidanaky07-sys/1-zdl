<?php
error_reporting(-1);

function debug($data)
{
    echo '<pre>' . print_r($data, 1) . '</pre>';
}

// ========== 1. Своя функция count() ==========
/*
 * Дан массив:
 * $nums = [1, 2, 3, 1, 4, 5, 3, 2, 6, 7, 7, 8, 8, 9, 2, 5,];
 * Напишите свой вариант функции count() - user_count() - которая будет принимать
 * аргументом одномерный массив и возвращать кол-во элементов массива (длину массива)
 */

$nums1 = [1, 2, 3, 1, 4, 5, 3, 2, 6, 7, 7, 8, 8, 9, 2, 5];

function user_count($arr)
{
    $count = 0;
    foreach ($arr as $item) {
        $count++;
    }
    return $count;
}

echo "Количество элементов в \$nums1: " . user_count($nums1) . "<br>\n"; // 16


// ========== 2. Сумма элементов массива ==========
/*
 * Дан массив:
 * $nums = [1, 2, 3, 1, 4, 5, 3, 2, 6, 7, 7, 8, 8, 9, 2, 5,];
 * Подсчитайте сумму значений элементов массива.
 * Попробуйте написать 2 варианта решения: со специальной функцией и без нее
 */

$nums2 = [1, 2, 3, 1, 4, 5, 3, 2, 6, 7, 7, 8, 8, 9, 2, 5];

// Вариант 1: без специальной функции
$sum1 = 0;
foreach ($nums2 as $value) {
    $sum1 += $value;
}
echo "Сумма (без функции): $sum1<br>\n";

// Вариант 2: со специальной функцией array_sum()
$sum2 = array_sum($nums2);
echo "Сумма (с array_sum): $sum2<br>\n";


// ========== 3. Количество четных чисел ==========
/*
 * Дан массив чисел.
 * Найдите количество четных чисел в массиве.
 * Сделайте 2 варианта решения: с функцией и без функции
 */

$nums3 = [1, 2, 3, 1, 4, 5, 3, 2, 6, 7, 7, 8, 8, 9, 2, 5];

// Вариант 1: без специальной функции
$evenCount1 = 0;
foreach ($nums3 as $value) {
    if ($value % 2 == 0) {
        $evenCount1++;
    }
}
echo "Количество четных чисел (без функции): $evenCount1<br>\n";

// Вариант 2: с использованием array_filter()
$evenArray = array_filter($nums3, function($num) {
    return $num % 2 == 0;
});
$evenCount2 = count($evenArray);
echo "Количество четных чисел (с array_filter): $evenCount2<br>\n";


// ========== 4. Массив от 1 до 100 ==========
/*
 * Создайте массив из чисел от 1 до 100.
 * Попробуйте написать 2 варианта решения:
 * 1) без специальной функции
 * 2) со специальной функцией
 */

// Вариант 1: без специальной функции (цикл)
$arr100_1 = [];
for ($i = 1; $i <= 100; $i++) {
    $arr100_1[] = $i;
}

// Вариант 2: со специальной функцией range()
$arr100_2 = range(1, 100);

// Вывод для проверки (первые 10 элементов)
echo "Массив 1..100 (первые 10): ";
for ($i = 0; $i < 10; $i++) {
    echo $arr100_2[$i] . " ";
}
echo "<br>\n";

echo "Длина массива: " . count($arr100_2) . "<br>\n";
